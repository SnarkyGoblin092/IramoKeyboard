    private static func path(for outlines: [String]) -> UIBezierPath {
        let path = UIBezierPath()
        path.usesEvenOddFillRule = true
        for outline in outlines {
            let v = outline.split(separator: " ").compactMap { Double($0) }
            guard v.count >= 6 else { continue }
            path.move(to: CGPoint(x: v[0], y: v[1]))
            var i = 2
            while i + 1 < v.count {
                path.addLine(to: CGPoint(x: v[i], y: v[i + 1]))
                i += 2
            }
            path.close()
        }
        return path
    }

