def write_json(name: str, data) -> None:
    (OUT / name).write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")


# Word counts of the languages other lists leak (English, Russian), for the leak filters. Read on first use, so
# languages can be built in any order and in separate processes.
reference_counts = {}


def reference(lang: str):
    if lang not in reference_counts:
        path = fetch(f"{lang}_full.txt", optional=True) or fetch(f"{lang}_50k.txt", optional=True)
        reference_counts[lang] = read_counts(path, lang) if path is not None else None
    return reference_counts[lang]


def build_language(lang: str, groups) -> None:
    required = lang in REQUIRED

    print(f"Emoji keywords ({lang}) …")
    try:
        annotation_file = fetch(f"annotations_{lang}.json", optional=not required)
        if annotation_file is None:
            raise RuntimeError("annotations not available")
        annotations = load_annotations(annotation_file, fetch(f"derived_{lang}.json", optional=True))
        keywords = build_keywords(groups, annotations)
        searchable = build_search(groups, annotations)
        print(f"  {len(keywords)} keywords, {len(searchable)} searchable emoji")
    except Exception as error:  # noqa: BLE001 - one language must not fail the build
        if required:
            raise
        print(f"  WARNING: no emoji keywords for {lang}: {error}")
        keywords, searchable = {}, {}
    write_json(f"emoji_keywords_{lang}.json", keywords)
    write_json(f"emoji_search_{lang}.json", searchable)
    build_dictionary(lang)


def build_dictionary(lang: str) -> None:
    """words_<lang>.tsv and pairs_<lang>.tsv. English (and Russian, for Ukrainian) must be built first: their
    counts filter leaked words out of the other languages."""
    required = lang in REQUIRED
    print(f"Words ({lang}) …")
    try:
        word_file = fetch(f"{lang}_full.txt", optional=True) or fetch(f"{lang}_50k.txt", optional=not required)
        if word_file is None:
            raise RuntimeError("word list not available")
        counts = read_counts(word_file, lang)
        if lang in {"en", "ru"}:
            reference_counts[lang] = counts
        if lang != "en":
            counts = drop_foreign(counts, reference("en"), "English")
        for other, name in LEAKS.get(lang, []):
            counts = drop_foreign(counts, reference(other), name)
        words = build_words(counts, lang, WORD_LIMITS.get(lang, DEFAULT_WORD_LIMIT))
        if not words and not required:
            raise RuntimeError("word list was empty after filtering")
    except Exception as error:  # noqa: BLE001
        if required:
            raise
        print(f"  WARNING: no word list for {lang}: {error}")
        words = []

    # Example sentences: misspellings to drop, word pairs and sentence starters. Without them the keyboard still
    # works; next-word suggestions then only come from what the user types.
    print(f"Sentences ({lang}) …")
    pairs = []
    try:
        sentences = fetch(f"sentences_{lang}.tsv.bz2", optional=True)
        if sentences is None or not words:
            raise RuntimeError("sentences not available")
        pair_counts, starts, seen = read_sentences(sentences, lang, {word for word, _, _ in words})
        words = drop_typos(words, seen)
        pairs = build_pairs(pair_counts, starts, seen, words)
        print(f"  {len(pairs[0][1])} sentence starters, {len(pairs) - 1} words with followers")
    except Exception as error:  # noqa: BLE001
        print(f"  WARNING: no sentences for {lang}: {error}")

    capitals = build_language_model(lang, words) if words else {}
    print(f"  {len(words)} words, {len(capitals)} written with capitals")
    # Fourth column: "T" = written Capitalised, "U" = written in CAPITALS ("i'm" -> I'm, "haus" -> Haus).
    with open(OUT / f"words_{lang}.tsv", "w", encoding="utf-8") as handle:
        for word, folded, count in words:
            handle.write(f"{word}\t{folded}\t{count}\t{capitals.get(word, '')}\n")
    with open(OUT / f"pairs_{lang}.tsv", "w", encoding="utf-8") as handle:
        for word, followers in pairs:
            handle.write(f"{word}\t{' '.join(followers)}\n")


def build_language_model(lang: str, words):
    """lm_<lang>.bin: word sequences from subtitles and the (not held-out) example sentences. Returns the words
    written with capitals (see Tokenizer.capitals)."""
    print(f"Language model ({lang}) …")
    ids = {}
    for index, (word, _, _) in enumerate(words):
        ids.setdefault(word, language_model.FIRST_WORD + index)
    tokenizer = language_model.Tokenizer(ids, lang, lower, repair)
    counts = language_model.Counts()
    subtitles = fetch(f"subtitles_{lang}.txt.gz", optional=True)
    if subtitles is not None:
        language_model.count_text(counts, tokenizer, language_model.subtitle_lines(subtitles))
    sentences = fetch(f"sentences_{lang}.tsv.bz2", optional=True)
    if sentences is not None:
        with bz2.open(sentences, "rt", encoding="utf-8", errors="ignore") as handle:
            rows = (line.rstrip("\n").split("\t") for line in handle)
            texts = (parts[2] for parts in rows if len(parts) >= 3 and not is_held_out(parts[0]))
            language_model.count_text(counts, tokenizer, texts, fresh_lines=True)
    if counts.tokens == 0:
        print(f"  WARNING: no text for the {lang} language model")
        return {}
    unigrams = [0] * language_model.FIRST_WORD + [count for _, _, count in words]
    bigrams, trigrams = language_model.build(counts, unigrams, OUT / f"lm_{lang}.bin")
    size = (OUT / f"lm_{lang}.bin").stat().st_size
    print(f"  {counts.tokens:,} words of text -> {bigrams:,} pairs, {trigrams:,} triples, {size / 1e6:.1f} MB")
    return tokenizer.capitals([word for word, _, _ in words])


