# Word pairs (next-word suggestions)
# ----------------------------------------------------------------------------

PAIR_FOLLOWERS = 3      # next words kept per word
PAIR_WORDS = 20000      # words that get followers (the ones that start the most pairs)
STARTERS = 12           # words that open sentences
CLAUSE_BREAK = re.compile(r"[.!?…;:,()\[\]{}\"“”„«»‹›—–]+")


def is_held_out(sentence_id: str) -> bool:
    """One sentence in 20 is kept out of the word pairs: scripts/predict_eval tests the keyboard on these."""
    return sentence_id.isdigit() and int(sentence_id) % 20 == 0


def read_sentences(path: Path, lang: str, vocabulary):
    """Counts in Tatoeba's example sentences (everyday text, and proofread): word pairs, sentence starters and how
    often each word occurs. Only dictionary words count; punctuation ends a run of words."""
    word_re = word_pattern(lang)
    pairs = collections.Counter()
    starts = collections.Counter()
    seen = collections.Counter()
    with bz2.open(path, "rt", encoding="utf-8", errors="ignore") as handle:
        for line in handle:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3 or is_held_out(parts[0]):
                continue
            first = True
            for clause in CLAUSE_BREAK.split(lower(parts[2], lang)):
                previous = None
                for token in clause.split():
                    token = repair(token.strip("'-"), lang)
                    known = token in vocabulary and word_re.match(token) is not None
                    if first:
                        if known:
                            starts[token] += 1
                        first = False
                    if not known:
                        previous = None
                        continue
                    seen[token] += 1
                    if previous is not None:
                        pairs[(previous, token)] += 1
                    previous = token
    return pairs, starts, seen


# A spelling that is common in subtitles but (nearly) absent from proofread text while a twin with the same
# letters is common there is a typo with its accents left out: Romanian "si" for "și", Polish "sie" for "się",
# Spanish "tambien" for "también". Dropping it lets the keyboard fix it and complete the right word. Real words
# that only differ by accents ("hat" / "hát", "si" / "sí", "schon" / "schön") are common in both.
TYPO_RATIO = 30
TYPO_MIN = 8      # the twin must be this common in the sentences for a decision


# Letters of their own, not accented ones: "воины" (warriors) is no misspelling of "войны" (wars).
OWN_LETTERS = set("йїЙЇ")


def is_stripped(typo: str, word: str) -> bool:
    """True when `typo` is `word` with some of its accents or its apostrophe left out, nothing else changed
    ("tambien" / "también", "dont" / "don't"; not "år" / "är" or "mütter" / "mutter")."""
    if typo == word or any(letter in OWN_LETTERS for letter in word):
        return False
    if typo == fold(word).replace("'", ""):
        return True
    return len(typo) == len(word) and all(t == w or t == fold(w) for t, w in zip(typo, word))


def drop_typos(words, seen):
    groups = collections.defaultdict(list)
    for word, folded, _ in words:
        groups[folded].append(word)
    typos = set()
    for spellings in groups.values():
        if len(spellings) < 2:
            continue
        usual = max(spellings, key=lambda word: seen.get(word, 0))
        best = seen.get(usual, 0)
        if best < TYPO_MIN:
            continue
        for word in spellings:
            # Rare in proofread text, and the usual word minus some accents.
            if seen.get(word, 0) * TYPO_RATIO < best and is_stripped(word, usual):
                typos.add(word)
    print(f"  dropped {len(typos)} misspellings")
    return [row for row in words if row[0] not in typos]


# Example sentences use a few names and places far more than real text does ("Tom", "Mary", "Boston"): a word
# this many times more common there than in the word list is left out of the pairs.
SENTENCE_BIAS = 8


def build_pairs(pairs, starts, seen, words):
    """[(".", sentence starters), (word, its most common next words), ...] (see `read_sentences`)."""
    frequency = {word: count for word, _, count in words}
    seen_total = max(sum(seen.values()), 1)
    words_total = max(sum(frequency.values()), 1)
    vocabulary = {word for word in frequency
                  if seen.get(word, 0) < 20
                  or seen[word] / seen_total <= SENTENCE_BIAS * frequency[word] / words_total}
    print(f"  left out {len(frequency) - len(vocabulary)} words the sentences overuse")
    followers = {}
    totals = collections.Counter()
    for (word, following), count in pairs.most_common():
        if count < 2:
            break
        if word not in vocabulary or following not in vocabulary:
            continue
        totals[word] += count
        chosen = followers.setdefault(word, [])
        if len(chosen) < PAIR_FOLLOWERS and following != word:
            chosen.append(following)
    result = [(".", [word for word, _ in starts.most_common() if word in vocabulary][:STARTERS])]
    result += [(word, followers[word]) for word, _ in totals.most_common(PAIR_WORDS) if followers[word]]
    return result


