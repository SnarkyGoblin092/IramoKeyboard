#!/usr/bin/env python3
"""Downloads and prepares the data files that get bundled into the keyboard.

Run from the repository root:

    python3 scripts/build_data.py

Outputs go to Keyboard/Resources/ (git-ignored, regenerated by CI on every build):

    emoji.json                  every fully-qualified emoji of the *latest* Unicode release,
                                grouped like the iOS picker, skin-tone variants folded under
                                their base emoji
    emoji_keywords_<lang>.json  keyword -> emoji   (from CLDR annotations, used for emoji suggestions)
    emoji_search_<lang>.json    emoji -> list of folded search words (used by the emoji search box)
    words_<lang>.tsv            word <TAB> accent-folded word <TAB> frequency

for every language in LANGS (en hu es fr de it pt nl pl cs ro tr ru uk sv). English and Hungarian are
required: if they fail, the build fails. For every other language a failed download only prints a warning
and writes an EMPTY file (so the file list is always complete and the keyboard simply has no suggestions
for that language).

Sources (downloaded at build time, nothing is checked into the repo):
    * https://unicode.org/Public/emoji/latest/emoji-test.txt
    * https://github.com/unicode-org/cldr-json            (CLDR annotations)
    * https://github.com/hermitdave/FrequencyWords        (OpenSubtitles 2018 word counts, CC-BY-SA-4.0;
                                                            the full lists, the 50k lists as a fallback)

For offline testing set HUNKEYS_FIXTURES=/some/dir containing the files named by url_for() below
(emoji-test.txt, annotations_<lang>.json, derived_<lang>.json, <lang>_full.txt or <lang>_50k.txt).
"""

