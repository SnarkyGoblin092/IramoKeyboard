def word_pattern(lang: str):
    alpha = ALPHABETS[lang]
    if lang in APOSTROPHE:
        return re.compile(f"^[{alpha}]+(?:'[{alpha}]+){{0,2}}$")
    return re.compile(f"^[{alpha}]+$")


# How many words each dictionary keeps. Languages that build words from many suffixes need far more forms
# ("billentyűzet", "billentyűzetet", "billentyűzeten" ... are all separate words).
WORD_LIMITS = {"hu": 160000, "tr": 140000, "pl": 100000, "cs": 100000, "ru": 100000, "uk": 100000, "ro": 90000}
DEFAULT_WORD_LIMIT = 80000
MIN_COUNT = 3   # rarer "words" in the full lists are mostly typos and names

# Subtitles keep songs and untranslated lines in English, so every list contains English words ("love", "that").
# Beyond the most common words, a word that is far more frequent in English than here is dropped.
ENGLISH_RATIO = 30
ENGLISH_PROTECTED_RANK = 1000


def lower(text: str, lang: str) -> str:
    """Lower-case the way the language does (Turkish I -> ı, İ -> i), with straight apostrophes."""
    if lang == "tr":
        text = text.replace("I", "ı").replace("İ", "i")
    return text.lower().replace("’", "'").replace("ʼ", "'")


def repair(word: str, lang: str) -> str:
    """Undoes code-page damage (see REPAIRS / HOMOGLYPHS)."""
    for wrong, right in REPAIRS.get(lang, []):
        if wrong in word:
            word = word.replace(wrong, right)
    table = HOMOGLYPHS.get(lang)
    if table is not None and (CYRILLIC.search(word) or word.isascii()):
        repaired = word.translate(table)
        # An all-Latin token only counts when it becomes all Cyrillic ("i" -> "і"), not an English word.
        if CYRILLIC.search(word) or not re.search("[a-z]", repaired):
            word = repaired
    return word


def read_counts(path: Path, lang: str):
    """word -> count for the words that pass the language's spelling filters."""
    word_re = word_pattern(lang)
    vowels = set(VOWELS[lang]) if VOWELS[lang] else None
    singles = SINGLES[lang]
    blocked = EN_BLOCK if lang == "en" else set()
    counts = {}
    with open(path, encoding="utf-8", errors="ignore") as handle:
        for line in handle:
            parts = line.strip().split()
            if len(parts) != 2 or not parts[1].isdigit():
                continue
            word, count = repair(lower(parts[0], lang), lang), int(parts[1])
            if count < MIN_COUNT:
                break    # the lists are sorted by count, so the rest is the rare tail
            if not word_re.match(word) or word in blocked:
                continue
            if len(word) == 1 and word not in singles:
                continue
            if vowels is not None and len(word) > 2 and not (set(word) & vowels) and word not in NO_VOWEL_OK:
                continue
            if re.search(r"(.)\1\1", word):
                continue
            counts[word] = counts.get(word, 0) + count
    return counts


def drop_foreign(counts, foreign, name: str):
    """Removes words of another language that leaked into this list (see ENGLISH_RATIO)."""
    if not counts or not foreign:
        return counts
    total = sum(counts.values())
    foreign_total = sum(foreign.values())
    ranked = sorted(counts.items(), key=lambda kv: -kv[1])
    kept = {}
    dropped = 0
    for rank, (word, count) in enumerate(ranked):
        share = foreign.get(word, 0) / foreign_total
        if rank >= ENGLISH_PROTECTED_RANK and share > ENGLISH_RATIO * count / total:
            dropped += 1
            continue
        kept[word] = count
    print(f"  dropped {dropped} {name} words")
    return kept


# Leaks besides English, by the same rule: Ukrainian subtitles are full of Russian ("что", "меня").
LEAKS = {"uk": [("ru", "Russian")]}


def build_words(counts, lang: str, limit: int):
    counts = dict(counts)
    if counts:
        reference = max(counts.values())
        for word, weight in CONTRACTIONS.get(lang, {}).items():
            counts[word] = max(counts.get(word, 0), int(weight * reference))
    ranked = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]
    # The folded column has no apostrophes, so "were" can find "we're" (the keyboard matches on it).
    return [(word, fold(word).replace("'", ""), count) for word, count in ranked]


