#!/usr/bin/env python3
"""Downloads and prepares the data files that get bundled into the keyboard.

Run from the repository root:

    python3 scripts/build_data.py

Outputs go to Keyboard/Resources/ (git-ignored, regenerated by CI on every build):

    emoji.json                  every fully-qualified emoji of the *latest* Unicode release,
                                grouped like the iOS picker, skin-tone variants folded under
                                their base emoji
    emoji_keywords_<lang>.json  keyword -> emoji   (from CLDR annotations, used for emoji suggestions)
    emoji_search_<lang>.json    emoji -> list of folded search words (used by the emoji search box)
    words_<lang>.tsv            word <TAB> accent-folded word <TAB> frequency

for every language in LANGS (en hu es fr de it pt nl pl cs ro tr ru uk sv). English and Hungarian are
required: if they fail, the build fails. For every other language a failed download only prints a warning
and writes an EMPTY file (so the file list is always complete and the keyboard simply has no suggestions
for that language).

Sources (downloaded at build time, nothing is checked into the repo):
    * https://unicode.org/Public/emoji/latest/emoji-test.txt
    * https://github.com/unicode-org/cldr-json            (CLDR annotations)
    * https://github.com/hermitdave/FrequencyWords        (OpenSubtitles 2018 word counts, CC-BY-SA-4.0)

For offline testing set HUNKEYS_FIXTURES=/some/dir containing the files named by url_for() below
(emoji-test.txt, annotations_<lang>.json, derived_<lang>.json, <lang>_50k.txt).
"""

import json
import os
import re
import subprocess
import sys
import time
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(os.environ.get("HUNKEYS_OUT", ROOT / "Keyboard" / "Resources"))
CACHE = Path(os.environ.get("HUNKEYS_CACHE", ROOT / ".data-cache"))

CLDR = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json"
FREQ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018"

LANGS = ["en", "hu", "es", "fr", "de", "it", "pt", "nl", "pl", "cs", "ro", "tr", "ru", "uk", "sv"]
REQUIRED = {"en", "hu"}


def url_for(name: str) -> str:
    if name == "emoji-test.txt":
        return "https://unicode.org/Public/emoji/latest/emoji-test.txt"
    match = re.fullmatch(r"annotations_([a-z]+)\.json", name)
    if match:
        return f"{CLDR}/cldr-annotations-full/annotations/{match.group(1)}/annotations.json"
    match = re.fullmatch(r"derived_([a-z]+)\.json", name)
    if match:
        return f"{CLDR}/cldr-annotations-derived-full/annotationsDerived/{match.group(1)}/annotations.json"
    match = re.fullmatch(r"([a-z]+)_50k\.txt", name)
    if match:
        return f"{FREQ}/{match.group(1)}/{name}"
    raise KeyError(name)


SKIN_TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}

GROUP_ICONS = {
    "Smileys & Emotion": "😀",
    "People & Body": "👋",
    "Animals & Nature": "🐻",
    "Food & Drink": "🍔",
    "Travel & Places": "🚗",
    "Activities": "⚽",
    "Objects": "💡",
    "Symbols": "🔣",
    "Flags": "🏁",
}


# ----------------------------------------------------------------------------
# Downloading
# ----------------------------------------------------------------------------

def download(url: str, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    last_error = ""
    for _ in range(3):
        result = subprocess.run(
            ["curl", "-fsSL", "--retry", "2", "--max-time", "180", "-o", str(dest), url],
            capture_output=True, text=True,
        )
        if result.returncode == 0 and dest.exists() and dest.stat().st_size > 0:
            return
        last_error = result.stderr.strip()
        time.sleep(2)
    raise RuntimeError(f"download failed: {url}\n{last_error}")


def fetch(name: str, optional: bool = False):
    fixtures = os.environ.get("HUNKEYS_FIXTURES")
    if fixtures:
        path = Path(fixtures) / name
        if path.exists():
            return path
        if optional:
            return None
        raise FileNotFoundError(path)
    dest = CACHE / name
    try:
        download(url_for(name), dest)
    except RuntimeError as error:
        if optional:
            print(f"  (optional) skipped {name}: {error}")
            return None
        raise
    return dest


