#!/usr/bin/env python3
"""Downloads and prepares the data files that get bundled into the keyboard.

Run from the repository root:

    python3 scripts/build_data.py

Outputs go to Keyboard/Resources/ (git-ignored, regenerated by CI on every build):

    emoji.json              every fully-qualified emoji of the *latest* Unicode release,
                            grouped like the iOS picker, skin-tone variants folded under
                            their base emoji
    emoji_keywords_en.json  keyword -> emoji   (from CLDR annotations, used for emoji suggestions)
    emoji_keywords_hu.json  same, in Hungarian
    emoji_search_en.json    emoji -> list of folded search words (used by the emoji search box)
    emoji_search_hu.json    same, Hungarian
    words_en.tsv            word <TAB> accent-folded word <TAB> frequency
    words_hu.tsv            same, Hungarian

Sources (downloaded at build time, nothing is checked into the repo):
    * https://unicode.org/Public/emoji/latest/emoji-test.txt
    * https://github.com/unicode-org/cldr-json            (CLDR annotations, en + hu)
    * https://github.com/hermitdave/FrequencyWords        (OpenSubtitles 2018 word counts, CC-BY-SA-4.0)

For offline testing set HUNKEYS_FIXTURES=/some/dir containing the files named in FILES below.
"""

import json
import os
import re
import subprocess
import sys
import time
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(os.environ.get("HUNKEYS_OUT", ROOT / "Keyboard" / "Resources"))
CACHE = Path(os.environ.get("HUNKEYS_CACHE", ROOT / ".data-cache"))

CLDR = "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json"
FREQ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018"

FILES = {
    "emoji-test.txt": "https://unicode.org/Public/emoji/latest/emoji-test.txt",
    "annotations_en.json": f"{CLDR}/cldr-annotations-full/annotations/en/annotations.json",
    "annotations_hu.json": f"{CLDR}/cldr-annotations-full/annotations/hu/annotations.json",
    "derived_en.json": f"{CLDR}/cldr-annotations-derived-full/annotationsDerived/en/annotations.json",
    "derived_hu.json": f"{CLDR}/cldr-annotations-derived-full/annotationsDerived/hu/annotations.json",
    "en_50k.txt": f"{FREQ}/en/en_50k.txt",
    "hu_50k.txt": f"{FREQ}/hu/hu_50k.txt",
}

SKIN_TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}

GROUP_ICONS = {
    "Smileys & Emotion": "😀",
    "People & Body": "👋",
    "Animals & Nature": "🐻",
    "Food & Drink": "🍔",
    "Travel & Places": "🚗",
    "Activities": "⚽",
    "Objects": "💡",
    "Symbols": "🔣",
    "Flags": "🏁",
}


# ----------------------------------------------------------------------------
# Downloading
# ----------------------------------------------------------------------------

def download(url: str, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    last_error = ""
    for _ in range(3):
        result = subprocess.run(
            ["curl", "-fsSL", "--retry", "2", "--max-time", "180", "-o", str(dest), url],
            capture_output=True, text=True,
        )
        if result.returncode == 0 and dest.exists() and dest.stat().st_size > 0:
            return
        last_error = result.stderr.strip()
        time.sleep(2)
    raise RuntimeError(f"download failed: {url}\n{last_error}")


def fetch(name: str, optional: bool = False):
    fixtures = os.environ.get("HUNKEYS_FIXTURES")
    if fixtures:
        path = Path(fixtures) / name
        if path.exists():
            return path
        if optional:
            return None
        raise FileNotFoundError(path)
    dest = CACHE / name
    try:
        download(FILES[name], dest)
    except RuntimeError as error:
        if optional:
            print(f"  (optional) skipped {name}: {error}")
            return None
        raise
    return dest


# ----------------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------------

def fold(text: str) -> str:
    """Lower-case and strip accents: 'Szép' -> 'szep'. Must match Swift's TextFolding."""
    decomposed = unicodedata.normalize("NFD", text.lower())
    return "".join(c for c in decomposed if unicodedata.category(c) != "Mn")


def has_skin_tone(emoji: str) -> bool:
    return any(ord(c) in SKIN_TONES for c in emoji)


def strip_skin_tone(emoji: str) -> str:
    return "".join(c for c in emoji if ord(c) not in SKIN_TONES)


def strip_fe0f(text: str) -> str:
    return text.replace("️", "")


# ----------------------------------------------------------------------------
# Emoji
# ----------------------------------------------------------------------------

LINE = re.compile(r"^([0-9A-Fa-f ]+?)\s*;\s*([a-z-]+)\s*#\s*(\S+)\s+E(\d+(?:\.\d+)?)\s+(.*)$")


def parse_emoji_test(path: Path):
    version = "unknown"
    groups = []
    current = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# Version:"):
            version = line.split(":", 1)[1].strip()
            continue
        if line.startswith("# group:"):
            current = {"name": line.split(":", 1)[1].strip(), "entries": []}
            groups.append(current)
            continue
        if not line or line.startswith("#") or current is None:
            continue
        match = LINE.match(line)
        if not match:
            continue
        codes, status, _glyph, _emoji_version, name = match.groups()
        if status != "fully-qualified":
            continue
        emoji = "".join(chr(int(code, 16)) for code in codes.split())
        current["entries"].append((emoji, name.strip()))
    return version, groups


def build_emoji_groups(raw_groups):
    """Folds skin-tone variants under their base emoji.

    Every emoji from emoji-test.txt survives: either as a base item, as a variant of
    one (long-press in the picker), or - if no base can be found - as its own item.
    """
    result = []
    for group in raw_groups:
        entries = group["entries"]
        if not entries:
            continue  # e.g. the "Component" group only has component-status lines

        base_items = {}      # emoji -> [emoji, variants...]
        base_by_name = {}    # CLDR name -> same list
        order = []
        for emoji, name in entries:
            if not has_skin_tone(emoji):
                item = [emoji]
                base_items[emoji] = item
                base_by_name[name] = item
                order.append(item)

        orphans = []
        for emoji, name in entries:
            if not has_skin_tone(emoji):
                continue
            target = base_items.get(strip_skin_tone(emoji))
            if target is None:
                # e.g. mixed-tone handshakes: "handshake: light skin tone, dark skin tone"
                target = base_by_name.get(name.split(":")[0].strip())
            if target is not None:
                target.append(emoji)
            else:
                orphans.append([emoji])

        items = order + orphans
        result.append({
            "name": group["name"],
            "icon": GROUP_ICONS.get(group["name"], items[0][0]),
            "items": items,
        })
    return result


def load_annotations(*paths):
    merged = {}
    for path in paths:
        if path is None:
            continue
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        root = data.get("annotations") or data.get("annotationsDerived") or {}
        entries = root.get("annotations", root)
        for key, value in entries.items():
            if isinstance(value, dict):
                merged.setdefault(strip_fe0f(key), value)
    return merged


WORD_ONLY = re.compile(r"^[^\W\d_]+$", re.UNICODE)


def build_keywords(groups, annotations, per_keyword=6):
    index = {}
    order = 0
    for group in groups:
        for item in group["items"]:
            base = item[0]
            order += 1
            if has_skin_tone(base):
                continue
            annotation = annotations.get(strip_fe0f(base))
            if not annotation:
                continue
            names = [n.lower() for n in annotation.get("tts", [])]
            for keyword in [k.lower() for k in annotation.get("default", [])] + names:
                if not WORD_ONLY.match(keyword):
                    continue  # multi-word phrases can never match a single typed word
                priority = 0 if keyword in names else 1
                index.setdefault(fold(keyword), []).append((priority, order, base))

    output = {}
    for keyword, hits in index.items():
        hits.sort()
        seen, emojis = set(), []
        for _priority, _order, emoji in hits:
            if emoji not in seen:
                seen.add(emoji)
                emojis.append(emoji)
            if len(emojis) >= per_keyword:
                break
        output[keyword] = emojis
    return output


def build_search(groups, annotations, per_emoji=16):
    """emoji -> folded words people might type to find it (names first, then keywords)."""
    result = {}
    splitter = re.compile(r"[\s:,;()\-\u2013\u2019'\"]+")
    for group in groups:
        for item in group["items"]:
            base = item[0]
            if has_skin_tone(base):
                continue
            annotation = annotations.get(strip_fe0f(base))
            if not annotation:
                continue
            words = []
            phrases = list(annotation.get("tts", [])) + list(annotation.get("default", []))
            for phrase in phrases:
                for piece in splitter.split(phrase.lower()):
                    folded = fold(piece.strip("."))
                    if len(folded) >= 2 and folded not in words:
                        words.append(folded)
            if words:
                result[base] = words[:per_emoji]
    return result


# ----------------------------------------------------------------------------
# Words
# ----------------------------------------------------------------------------

EN_WORD = re.compile(r"^[a-z]+(?:'[a-z]+)?$")
HU_WORD = re.compile(r"^[a-záéíóöőúüű]+$")
EN_VOWELS = set("aeiouy")
HU_VOWELS = set("aeiouyáéíóöőúüű")
NO_VOWEL_OK = {"hm", "hmm", "mr", "mrs", "ms", "dr", "tv", "pm", "cd", "dj", "mm", "sh", "shh", "psst"}
EN_BLOCK = {"ll", "ve", "re", "didn", "doesn", "isn", "wasn", "weren", "hasn", "haven",
            "hadn", "couldn", "wouldn", "shouldn", "aren", "ain", "mustn", "needn"}
LANGS = {
    "en": (EN_WORD, EN_VOWELS, {"a", "i"}, EN_BLOCK),
    "hu": (HU_WORD, HU_VOWELS, {"a", "e", "s"}, set()),
}


def build_words(path: Path, lang: str, limit: int = 40000):
    word_re, vowels, singles, blocked = LANGS[lang]
    counts = {}
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        parts = line.strip().split()
        if len(parts) != 2 or not parts[1].isdigit():
            continue
        word, count = parts[0].lower(), int(parts[1])
        if not word_re.match(word) or word in blocked:
            continue
        if len(word) == 1 and word not in singles:
            continue
        if len(word) > 2 and not (set(word) & vowels) and word not in NO_VOWEL_OK:
            continue
        if re.search(r"(.)\1\1", word):
            continue
        counts[word] = counts.get(word, 0) + count
    ranked = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]
    return [(word, fold(word), count) for word, count in ranked]


# ----------------------------------------------------------------------------

def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)

    print("Emoji …")
    version, raw_groups = parse_emoji_test(fetch("emoji-test.txt"))
    groups = build_emoji_groups(raw_groups)
    total = sum(len(g["items"]) for g in groups)
    variants = sum(len(i) - 1 for g in groups for i in g["items"])
    (OUT / "emoji.json").write_text(
        json.dumps({"version": version, "groups": groups}, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )
    print(f"  Unicode emoji {version}: {total} items + {variants} variants in {len(groups)} groups")

    for lang in ("en", "hu"):
        print(f"Emoji keywords ({lang}) …")
        annotations = load_annotations(
            fetch(f"annotations_{lang}.json"),
            fetch(f"derived_{lang}.json", optional=True),
        )
        keywords = build_keywords(groups, annotations)
        (OUT / f"emoji_keywords_{lang}.json").write_text(
            json.dumps(keywords, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
        searchable = build_search(groups, annotations)
        (OUT / f"emoji_search_{lang}.json").write_text(
            json.dumps(searchable, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
        print(f"  {len(keywords)} keywords, {len(searchable)} searchable emoji")

    for lang in ("en", "hu"):
        print(f"Words ({lang}) …")
        words = build_words(fetch(f"{lang}_50k.txt"), lang)
        with open(OUT / f"words_{lang}.tsv", "w", encoding="utf-8") as handle:
            for word, folded, count in words:
                handle.write(f"{word}\t{folded}\t{count}\n")
        print(f"  {len(words)} words")

    print("Done ->", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
