def url_for(name: str) -> str:
    if name == "emoji-test.txt":
        return "https://unicode.org/Public/emoji/latest/emoji-test.txt"
    match = re.fullmatch(r"annotations_([a-z]+)\.json", name)
    if match:
        return f"{CLDR}/cldr-annotations-full/annotations/{match.group(1)}/annotations.json"
    match = re.fullmatch(r"derived_([a-z]+)\.json", name)
    if match:
        return f"{CLDR}/cldr-annotations-derived-full/annotationsDerived/{match.group(1)}/annotations.json"
    match = re.fullmatch(r"([a-z]+)_(?:50k|full)\.txt", name)
    if match:
        return f"{FREQ}/{match.group(1)}/{name}"
    match = re.fullmatch(r"sentences_([a-z]+)\.tsv\.bz2", name)
    if match:
        iso3 = ISO3[match.group(1)]
        return f"{TATOEBA}/{iso3}/{iso3}_sentences.tsv.bz2"
    match = re.fullmatch(r"subtitles_([a-z]+)\.txt\.gz", name)
    if match:
        return f"{OPUS}/{match.group(1)}.txt.gz"
    raise KeyError(name)


