def build_language(lang: str, groups) -> None:
    required = lang in REQUIRED

    print(f"Emoji keywords ({lang}) …")
    try:
        annotation_file = fetch(f"annotations_{lang}.json", optional=not required)
        if annotation_file is None:
            raise RuntimeError("annotations not available")
        annotations = load_annotations(annotation_file, fetch(f"derived_{lang}.json", optional=True))
        keywords = build_keywords(groups, annotations)
        searchable = build_search(groups, annotations)
        print(f"  {len(keywords)} keywords, {len(searchable)} searchable emoji")
    except Exception as error:  # noqa: BLE001 - one language must not fail the build
        if required:
            raise
        print(f"  WARNING: no emoji keywords for {lang}: {error}")
        keywords, searchable = {}, {}
    write_json(f"emoji_keywords_{lang}.json", keywords)
    write_json(f"emoji_search_{lang}.json", searchable)

    print(f"Words ({lang}) …")
    try:
        word_file = fetch(f"{lang}_full.txt", optional=True) or fetch(f"{lang}_50k.txt", optional=not required)
        if word_file is None:
            raise RuntimeError("word list not available")
        counts = read_counts(word_file, lang)
        if lang == "en":
            english_counts.update(counts)
        else:
            counts = drop_english(counts, english_counts)
        words = build_words(counts, lang, WORD_LIMITS.get(lang, DEFAULT_WORD_LIMIT))
        if not words and not required:
            raise RuntimeError("word list was empty after filtering")
        print(f"  {len(words)} words")
    except Exception as error:  # noqa: BLE001
        if required:
            raise
        print(f"  WARNING: no word list for {lang}: {error}")
        words = []
    with open(OUT / f"words_{lang}.tsv", "w", encoding="utf-8") as handle:
        for word, folded, count in words:
            handle.write(f"{word}\t{folded}\t{count}\n")


